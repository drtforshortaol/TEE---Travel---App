function unique(vals){ return [...new Set(vals)].filter(Boolean).sort(); }
function slug(s){ return String(s).toLowerCase().replace(/&/g,'and').replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,''); }
function groupId(g){ return `${slug(g.country)}-${slug(g.language)}-${slug(g.category)}`; }
function displayCategory(g){ return CATEGORY_LABELS[g.category] || g.category; }
function displayTitle(g){
  if(g.country === 'Slovenia') return `Slovenia — ${displayCategory(g)}`;
  if(g.country === 'Switzerland' && g.language.toLowerCase().includes('french')) return `Switzerland — French backup — ${displayCategory(g)}`;
  return `${g.country} — ${displayCategory(g)}`;
}
function addOptions(select, vals){
  vals.forEach(v=>{ const o=document.createElement('option'); o.value=v; o.textContent=v; select.appendChild(o); });
}
function phraseText(g){ return [g.country,g.language,g.category,displayTitle(g),g.note,...g.phrases.flat()].join(' ').toLowerCase(); }
function matches(g){
  const q = searchInput.value.trim().toLowerCase();
  return (!q || phraseText(g).includes(q)) &&
    (countryFilter.value === 'all' || g.country === countryFilter.value) &&
    (categoryFilter.value === 'all' || g.category === categoryFilter.value);
}
function setFilters(country='all', category='all', options={}){
  searchInput.value = '';
  countryFilter.value = country;
  categoryFilter.value = category;
  if(options.openGroupId) pendingOpenGroupId = options.openGroupId;
  render();
  if(options.collapseIndex !== false) collapseGroupIndex();
}
function scrollToGroup(id){
  const target = document.getElementById(id);
  if(!target) return;
  target.classList.add('open');
  const btn = target.querySelector(':scope > .travel-accordion-toggle');
  if(btn) btn.setAttribute('aria-expanded','true');
  target.scrollIntoView({behavior:'smooth', block:'start'});
}
function goToGroup(g){
  const id = groupId(g);
  setFilters(g.country, g.category, {openGroupId:id, collapseIndex:true});
  history.replaceState(null, '', `#${id}`);
  setTimeout(()=>scrollToGroup(id), 80);
}
function renderSummary(groups){
  const phraseCount = groups.reduce((n,g)=>n+g.phrases.length,0);
  summaryMount.innerHTML = `
    <article class="summary-card"><div class="num">${groups.length}</div><div class="label">Phrase sections shown</div><p>Each section is a larger tappable card, designed to convert cleanly into a future PDF page.</p></article>
    <article class="summary-card"><div class="num">${phraseCount}</div><div class="label">Phrases shown</div><p>English meaning + local phrase + pronunciation/note.</p></article>
    <article class="summary-card"><div class="num">${unique(groups.map(g=>g.country)).length}</div><div class="label">Countries shown</div><p>Turkey, Croatia, Slovenia, Austria, and Switzerland.</p></article>`;
}
function indexGroups(){
  return PHRASE_GROUPS.filter(g =>
    (countryFilter.value === 'all' || g.country === countryFilter.value) &&
    (categoryFilter.value === 'all' || g.category === categoryFilter.value)
  );
}
function renderGroupIndex(){
  if(!groupMount) return;
  const groups = indexGroups();
  groupMount.innerHTML = groups.map(g => `
    <button type="button" class="group-jump" data-id="${groupId(g)}">
      <span class="jump-title">${displayTitle(g)}</span>
      <span class="jump-subtitle">${g.language} · ${g.phrases.length} phrases</span>
    </button>`).join('');
  if(!groups.length) groupMount.innerHTML = '<p class="empty index-empty">No phrase-section choices match the current country/group filters.</p>';
  groupMount.querySelectorAll('button[data-id]').forEach(btn=>{
    const g = PHRASE_GROUPS.find(x => groupId(x) === btn.dataset.id);
    if(g) btn.addEventListener('click',()=>goToGroup(g));
  });
}
function renderQuickNav(){
  const countries = unique(PHRASE_GROUPS.map(g=>g.country));
  countryMount.innerHTML = countries.map(country => {
    const label = COUNTRY_LANGUAGE_LABEL[country] || country;
    return `<button type="button" class="nav-chip country-chip" data-country="${country}"><strong>${country}</strong><span>${label}</span></button>`;
  }).join('');
  countryMount.querySelectorAll('button[data-country]').forEach(btn=>{
    btn.addEventListener('click',()=>setFilters(btn.dataset.country,'all', {collapseIndex:true}));
  });
  setupGroupIndexPanel();
  renderGroupIndex();
}
function setupGroupIndexPanel(){
  if(!groupPanel || groupPanel.dataset.indexReady === '1') return;
  const heading = groupPanel.querySelector('h2');
  const title = heading ? heading.textContent.trim() : 'Phrase Section Index';
  if(heading) heading.remove();
  const toggle = document.createElement('button');
  toggle.type = 'button';
  toggle.id = 'groupIndexToggle';
  toggle.className = 'index-toggle';
  toggle.setAttribute('aria-controls','groupMount');
  toggle.setAttribute('aria-expanded','false');
  toggle.innerHTML = `<span><strong>${title}</strong><span class="index-toggle-hint">Collapsed by default. Open this to choose a phrase section.</span></span><span class="index-toggle-status">Show choices</span>`;
  groupPanel.insertBefore(toggle, groupPanel.firstChild);
  toggle.addEventListener('click',()=>setGroupIndexOpen(!groupIndexOpen));
  groupPanel.dataset.indexReady = '1';
  setGroupIndexOpen(false);
}
