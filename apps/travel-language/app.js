function setGroupIndexOpen(open){
  groupIndexOpen = Boolean(open);
  if(!groupPanel) return;
  groupPanel.classList.add('collapsible-index','ready');
  groupPanel.classList.toggle('open', groupIndexOpen);
  const btn = groupPanel.querySelector('#groupIndexToggle');
  if(btn){
    btn.setAttribute('aria-expanded', groupIndexOpen ? 'true' : 'false');
    const status = btn.querySelector('.index-toggle-status');
    if(status) status.textContent = groupIndexOpen ? 'Hide choices' : 'Show choices';
  }
}

function collapseGroupIndex(){ setGroupIndexOpen(false); }

